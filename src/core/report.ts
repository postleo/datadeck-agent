import type { CleanResult, PreAnalysis, FlagRecord, FlagReason } from './types';
import { horizontalBarChart, correlationBarChart, COLORS, type BarDatum } from './charts';

const FLAG_TITLES: Record<FlagReason, string> = {
  ambiguous_date: 'Ambiguous dates',
  unmappable_category: 'Labels that need a decision',
  possible_outlier: 'Possible outliers',
  mixed_currency: 'Mixed currencies',
  missing_in_complete_column: 'Missing values in otherwise-complete columns',
  failed_validation: 'Values that failed a validation rule',
  semantic_anomaly: 'Values that look wrong for what the column means',
};

