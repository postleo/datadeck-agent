// ─────────────────────────────────────────────────────────────
// DataDeck Agent — styled task-report email
//
// Renders a brand-styled HTML email (inline CSS, email-client safe) and sends
// it best-effort via Resend (RESEND_API_KEY). The rendered HTML is always
// written to the project folder as email.html, so the report exists whether or
// not a provider is configured. No secret values are ever logged.
// ─────────────────────────────────────────────────────────────
export interface EmailStat { label: string; value: string | number; }
export interface EmailLink { label: string; url: string; }
export interface EmailData {
  datasetName: string;
  headline: string;
  stats: EmailStat[];
  links: EmailLink[];
  siteUrl?: string;           // deployed multipage site (Vercel), if any
  generatedAt: string;
}

const INK = '#0C1D1B', AQUA6 = '#0E9C8E', AQUA1 = '#DCF5F1', MUT = '#5C7370', LINE = '#DDE8E7', ACC = '#F5C948';

