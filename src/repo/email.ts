/** Plain-markdown failure report written to the project folder as FAILED.md. */
export function renderFailureReport(f: FailureInfo): string {
  return [
    `# DataDeck — could not process ${f.datasetName}`, '',
    `_${f.generatedAt}_`, '',
    '> The DataDeck Agent hit a problem and stopped. Your source file was **not changed**,',
    '> and no values were guessed or rule-cleaned. This is a genuine failure notice, not a partial result.', '',
    '## What happened',
    `- **Stage:** ${f.stage}`,
    `- **Reason:** ${f.reason}`,
    `- **Source file:** \`${f.source}\``,
    `- **Project folder:** \`${f.project}\``, '',
    '## What to do',
    '1. Confirm an AI model is configured — a Gemini API key (`GEMINI_API_KEY`) or Amazon Bedrock access.',
    '   This agent reasons about your data with a model; it will not fall back to blind rule-cleaning.',
    '2. Re-add the file to the inbox to try again. A previously failed dataset is retried automatically.',
    '3. If it keeps failing, check the run logs for the underlying error.', '',
  ].join('\n');
}

/** Plain-markdown task report written to the project folder. */
export function renderTaskReport(d: EmailData, extra: { project: string; email: SendResult; site?: string }): string {
  const lines = [
    `# DataDeck task report — ${d.datasetName}`, '',
    `_${d.generatedAt}_`, '',
    `**${d.headline}**`, '',
    '## Summary', ...d.stats.map((s) => `- ${s.label}: ${s.value}`), '',
    '## Deliverables', ...d.links.map((l) => `- [${l.label}](${l.url})`),
    ...(extra.site ? [`- [Interactive report (deployed)](${extra.site})`] : []), '',
    '## Delivery',
    `- Project folder: \`${extra.project}\``,
    `- Email: ${extra.email.sent ? `sent via ${extra.email.provider}` + (extra.email.id ? ` (id ${extra.email.id})` : '') : `not sent (${extra.email.error})`}`,
    `- Site deploy: ${extra.site ? extra.site : 'not deployed'}`,
    '',
  ];
  return lines.join('\n');
}
